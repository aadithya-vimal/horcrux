"""First-class deterministic security-property registry.

The semantic heart of HORCRUX. Modeled around security properties, never
around scanner names. Each property declares its full contract: required
evidence, test methods, asset types, prerequisites, oracle, thresholds,
confirmation/refutation/blocked conditions, severity model, remediation.
"""

from __future__ import annotations

from pydantic import BaseModel, Field


class SecurityProperty(BaseModel):
    property_id: str
    category: str
    title: str
    required_evidence: list[str] = Field(default_factory=list)
    test_methods: list[str] = Field(default_factory=list)
    required_asset_types: list[str] = Field(default_factory=list)
    prerequisites: list[str] = Field(default_factory=list)
    oracle: str = ""
    min_evidence_threshold: int = 2
    confirmation_conditions: list[str] = Field(default_factory=list)
    refutation_conditions: list[str] = Field(default_factory=list)
    blocked_conditions: list[str] = Field(default_factory=list)
    severity: str = "medium"
    remediation: str = ""


def _p(pid: str, cat: str, title: str, **kw) -> SecurityProperty:
    return SecurityProperty(property_id=pid, category=cat, title=title, **kw)


