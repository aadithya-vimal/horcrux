REGISTRY: dict[str, SecurityProperty] = {p.property_id: p for p in PROPERTIES}


def get_property(pid: str) -> SecurityProperty | None:
    return REGISTRY.get(pid)


def properties_for_category(category: str) -> list[SecurityProperty]:
    return [p for p in PROPERTIES if p.category == category]


def all_property_ids() -> list[str]:
    return sorted(REGISTRY)
